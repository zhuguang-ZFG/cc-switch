#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Alias a requested model id to another id a channel actually serves, and drop
model ids the channel can no longer serve at all.

Found while reviving the opencode zen free pool on 2026-10-11: upstream deprecated
exo-free (CLI run returns `Error: Model exo-free has been deprecated.`, bare
`opencode/exo` returns UnknownError, /zen raw HTTP is 403 FreeTierError, /zen/go raw
HTTP is 400 Model is unavailable, and the id has zero log rows ever). The user still
wants the exo-free entry, so instead of deleting it we map it to a live free model —
the same {"public":"upstream"} mapping shape ch3/ch9 use for zg-claude-opus-5.

model_mapping and models are channels-only metadata, so both go through a direct
UPDATE: this fork's channel PUT round-trips key:"" back out of GET and wipes the
stored key. Abilities rows are normally regenerated by the channel update path, so
dropped ids are deleted here by hand, scoped by model (never by channel_id alone —
see docs/ops/omp-driftfix-dsv4f-head-2026-10-10.md).

Usage:
  set_channel_model_alias.py --channel 178 --alias exo-free=nemotron-3.5-lightning-free \
      --drop fledge-alpha-free [--drop ...] [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import sqlite3
import sys
import time
from contextlib import closing
from pathlib import Path
from typing import NoReturn

DB_PATH = Path.home() / ".new-api-local" / "new-api.db"
BACKUP_PREFIX = "new-api-before-model-alias"
COLS = ("models", "model_mapping")


def fatal(msg: str) -> NoReturn:
    print(f"ERROR: {msg}", flush=True)
    sys.exit(1)


def log(msg: str) -> None:
    print(msg, flush=True)


def channel_row(db: sqlite3.Connection, cid: int) -> dict:
    row = db.execute(
        "SELECT id, name, status, auto_ban, \"group\", models, model_mapping, length(key) AS key_len"
        " FROM channels WHERE id = ?",
        (cid,),
    ).fetchone()
    if row is None:
        fatal(f"channel {cid} not found")
    return dict(row)


def parse_mapping(raw: str | None) -> dict[str, str]:
    try:
        data = json.loads(raw or "{}")
    except ValueError:
        fatal(f"model_mapping is not valid json: {str(raw)[:80]}")
    if not isinstance(data, dict):
        fatal(f"model_mapping is not an object: {str(raw)[:80]}")
    return {str(k): str(v) for k, v in data.items()}


def split_models(raw: str | None) -> list[str]:
    return [m.strip() for m in (raw or "").split(",") if m.strip()]


def backup_db(src: sqlite3.Connection) -> Path:
    backup_dir = DB_PATH.parent / "backups"
    backup_dir.mkdir(parents=True, exist_ok=True)
    dest = backup_dir / f"{BACKUP_PREFIX}-{time.strftime('%Y%m%d-%H%M%S')}.db"
    with closing(sqlite3.connect(dest.as_posix())) as dst:
        src.backup(dst)
    return dest


def snapshot_channels(db: sqlite3.Connection) -> dict[int, tuple]:
    return {
        r["id"]: tuple(r[c] for c in COLS)
        for r in db.execute(f'SELECT id, {", ".join(COLS)} FROM channels')
    }


def snapshot_abilities(db: sqlite3.Connection) -> set[tuple[str, int, str]]:
    return {
        (r[0], r[1], r[2])
        for r in db.execute('SELECT model, channel_id, "group" FROM abilities')
    }


def restore_ability(db: sqlite3.Connection, cid: int, group: str, model: str) -> int:
    """Re-create an abilities row for a re-added id, copying routing numbers from a
    sibling row of the same channel so nothing is invented."""
    sib = db.execute(
        "SELECT enabled, priority, weight FROM abilities WHERE channel_id = ? AND \"group\" = ?"
        " ORDER BY model LIMIT 1",
        (cid, group),
    ).fetchone()
    if sib is None:
        fatal(f"ch{cid}: no {group!r} abilities row left to copy routing numbers from")
    return db.execute(
        "INSERT INTO abilities (\"group\", model, channel_id, enabled, priority, weight)"
        " VALUES (?, ?, ?, ?, ?, ?)",
        (group, model, cid, sib["enabled"], sib["priority"], sib["weight"]),
    ).rowcount


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--channel", type=int, required=True)
    parser.add_argument("--alias", dest="aliases", metavar="REQ=UPSTREAM", action="append", default=[],
                        help="serve REQ by sending UPSTREAM upstream (repeatable)")
    parser.add_argument("--drop", dest="drops", action="append", default=[],
                        help="model id the channel cannot serve: remove from models and abilities")
    parser.add_argument("--add", dest="adds", action="append", default=[],
                        help="model id to serve again: re-add to models and abilities")
    parser.add_argument("--unalias", dest="unaliases", action="append", default=[],
                        help="requested id to stop aliasing (keeps it serving its own name)")
    parser.add_argument("--dry-run", action="store_true", help="print plan only, do not write")
    args = parser.parse_args()

    if not (args.aliases or args.drops or args.adds or args.unaliases):
        fatal("nothing to do: pass --alias, --unalias, --drop and/or --add")

    if not DB_PATH.exists():
        fatal(f"DB not found: {DB_PATH}")

    with closing(sqlite3.connect(DB_PATH.as_posix(), timeout=30)) as db:
        db.row_factory = sqlite3.Row
        cur = channel_row(db, args.channel)
        owned = split_models(cur["models"])
        mapping = parse_mapping(cur["model_mapping"])

        for model in args.adds:
            if model not in owned:
                owned.append(model)

        wanted = {**mapping, **dict(spec.split("=", 1) for spec in args.aliases)}
        for req in args.unaliases:
            if req not in mapping and req not in wanted:
                fatal(f"ch{args.channel} has no alias for {req!r}; mapping is {cur['model_mapping'] or '{}'}")
            wanted.pop(req, None)
        for spec in args.aliases:
            req, _, up = spec.partition("=")
            if req not in owned:
                owned.append(req)
            if up not in owned:
                fatal(f"ch{args.channel} does not carry alias target {up!r}; carries {owned}")

        drops = [d for d in args.drops if d in owned and d not in set(args.adds)]
        missed = [d for d in args.drops if d not in owned]
        after = [m for m in owned if m not in set(drops)]
        new_models = ",".join(after)
        new_mapping = json.dumps(wanted, ensure_ascii=False, separators=(",", ":")) if wanted else ""

        log(f"ch{args.channel} {cur['name']!r} status={cur['status']} auto_ban={cur['auto_ban']} "
            f"group={cur['group']!r} key_len={cur['key_len']}")
        log(f"  models: {len(owned)} -> {len(after)}")
        for spec in args.aliases:
            log(f"  alias: {spec}  (upstream {cur['group']} group reaches this channel only for the requested id)")
        log(f"  re-add abilities: {args.adds or 'none'}")
        log(f"  un-alias: {args.unaliases or 'none'}")
        log(f"  drop: {drops or 'none'}{('; already absent: ' + str(missed)) if missed else ''}")
        log(f"  model_mapping: {cur['model_mapping'] or '{}'} -> {new_mapping or '{}'}")

        if args.dry_run:
            log("dry-run only, nothing written.")
            return 0

        ch_before = snapshot_channels(db)
        ab_before = snapshot_abilities(db)
        backup = backup_db(db)
        log(f"backup: {backup.name}")

        db.execute("BEGIN IMMEDIATE")
        try:
            touched = db.execute(
                "UPDATE channels SET models = ?, model_mapping = ? WHERE id = ?",
                (new_models, new_mapping, args.channel),
            ).rowcount
            if touched != 1:
                raise RuntimeError(f"expected 1 channel row, touched {touched}")
            for model in drops:
                removed = db.execute(
                    'DELETE FROM abilities WHERE channel_id = ? AND model = ?',
                    (args.channel, model),
                ).rowcount
                log(f"  abilities drop {model}: removed {removed} row(s)")
            for model in args.adds:
                exists = db.execute(
                    'SELECT 1 FROM abilities WHERE channel_id = ? AND model = ? AND "group" = ?',
                    (args.channel, model, cur["group"]),
                ).fetchone()
                if exists:
                    log(f"  abilities re-add {model}: row already present, left as is")
                else:
                    log(f"  abilities re-add {model}: inserted "
                        f"{restore_ability(db, args.channel, cur['group'], model)} row(s)")
            db.commit()
        except Exception as exc:
            db.rollback()
            fatal(f"write failed, rolled back (backup {backup.name}): {exc}")

        ch_after = snapshot_channels(db)
        ab_after = snapshot_abilities(db)
        drift = [cid for cid in ch_after if ch_before.get(cid) != ch_after[cid]]
        if drift != [args.channel]:
            fatal(f"collateral damage on channels {drift}; restore from {backup.name}")
        lost = ab_before - ab_after
        gained = ab_after - ab_before
        expect_lost = {(m, args.channel, cur["group"]) for m in drops}
        expect_gained = {(m, args.channel, cur["group"]) for m in args.adds}
        if lost - expect_lost or gained - expect_gained:
            fatal(f"abilities drift outside the requested drop/add sets: lost={sorted(lost - expect_lost)} "
                  f"gained={sorted(gained - expect_gained)}; restore from {backup.name}")

        check = channel_row(db, args.channel)
        if check["models"] != new_models or parse_mapping(check["model_mapping"]) != wanted:
            fatal(f"read-back mismatch on ch{args.channel}; restore from {backup.name}")
        if check["key_len"] != cur["key_len"]:
            fatal(f"ch{args.channel} key length changed ({cur['key_len']} -> {check['key_len']}); "
                  f"restore from {backup.name}")
        log(f"verified: models={len(after)} ids, mapping={new_mapping or '{}'}, key intact ({check['key_len']} bytes)")
        log(f"DONE. rollback backup: {backup.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
